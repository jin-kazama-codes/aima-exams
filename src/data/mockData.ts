function buildHallSeats(
  hallCode: string,
  capacity: number,
  isGroundFloor: boolean,
  accessibilityCount: number,
  reservedSeats: number[],
  preAllocated: { seat: string; candidateId: string; name: string; rollNumber: string }[]
): HallSeat[] {
  const seats: HallSeat[] = [];
  const cols = 8;
  for (let i = 1; i <= capacity; i++) {
    const seatNumber = String(i).padStart(3, '0');
    const row = Math.ceil(i / cols);
    const col = ((i - 1) % cols) + 1;
    const isAccessibilityZone = isGroundFloor && i <= accessibilityCount;
    const foundAlloc = preAllocated.find((a) => a.seat === seatNumber);

    let status: HallSeat['status'] = 'vacant';
    if (foundAlloc) {
      status = 'allocated';
    } else if (reservedSeats.includes(i)) {
      status = 'reserved';
    } else if (isAccessibilityZone) {
      status = 'accessibility';
    }

    seats.push({
      seatNumber,
      row,
      col,
      status,
      candidateId: foundAlloc?.candidateId,
      candidateName: foundAlloc?.name,
      rollNumber: foundAlloc?.rollNumber,
      isAccessibilityZone,
    });
  }
  return seats;
}

